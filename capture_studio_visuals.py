            base_img = Image.open(studio_png).convert("RGBA")
            # Scale to standard GIF resolution (960x600)
            base_scaled = base_img.resize((960, 600), Image.Resampling.LANCZOS)

            # Oscilloscope box coordinates in scaled image:
            # Original dock height = 140 at bottom of 900 -> y ~ 760..890
            # Let's draw animated waves into the canvas area
            # In 960x600: dock y starts around ~506
            for frame_idx in range(24):
                frame = base_scaled.copy()
                draw = ImageDraw.Draw(frame)

                # Draw oscillating green waveform in oscilloscope canvas (approx x: 10..196, y: 520..580)
                osc_x0, osc_y0, osc_w, osc_h = 16, 526, 186, 58
                draw.rectangle([osc_x0, osc_y0, osc_x0 + osc_w, osc_y0 + osc_h], fill="#11141e")
                draw.line([osc_x0, osc_y0 + osc_h / 2, osc_x0 + osc_w, osc_y0 + osc_h / 2], fill="#1e293b", width=1)

                wave_pts = []
                freq = 2.0 + (frame_idx % 8) * 0.2
                phase = frame_idx * 0.35
                for xi in range(osc_w):
                    t = xi / osc_w
                    y_val = math.sin(2 * math.pi * freq * t + phase) * 0.4
                    # Add 2nd harmonic
                    y_val += math.sin(4 * math.pi * freq * t + phase * 1.5) * 0.15
                    yi = osc_y0 + (0.5 - y_val) * osc_h
                    wave_pts.append((osc_x0 + xi, yi))
                if len(wave_pts) > 1:
                    draw.line(wave_pts, fill="#10b981", width=2)

                # Draw spectrum bars in FFT canvas (approx x: 212..398, y: 526..584)
                spec_x0, spec_y0, spec_w, spec_h = 212, 526, 186, 58
                draw.rectangle([spec_x0, spec_y0, spec_x0 + spec_w, spec_y0 + spec_h], fill="#11141e")

                num_bars = 28
                bw = spec_w / num_bars
                for bi in range(num_bars):
                    bar_decay = math.exp(-bi / 8.0)
                    pulse = math.sin(frame_idx * 0.4 + bi * 0.6) * 0.2 + 0.8
                    bh = (bar_decay * pulse) * (spec_h - 6)
                    bx = spec_x0 + bi * bw
                    by = spec_y0 + spec_h - bh
                    draw.rectangle([bx, by, bx + bw - 2, spec_y0 + spec_h], fill="#06b6d4")

                frame_file = os.path.join(frames_dir, f"frame_{frame_idx:03d}.png")
