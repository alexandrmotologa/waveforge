"""Tests for standalone C99 code generation and native compilation with clang."""

import os
import pytest
from waveforge.graph.patch import NodeGraph
from waveforge.graph.presets import create_acid_303_patch
from waveforge.codegen.c_generator import CCodeGenerator
from waveforge.codegen.wasm_builder import CCompilerDriver


def test_c_code_generation_structure():
    g = create_acid_303_patch()
    gen = CCodeGenerator(g)
    c_code = gen.generate_header(guard_name="TEST_SYNTH_H")

    # Verify essential C symbols and structures
    assert "#ifndef TEST_SYNTH_H" in c_code
    assert "typedef struct {" in c_code
    assert "WaveForgeSynth;" in c_code
    assert "void waveforge_synth_init(WaveForgeSynth* s, float sample_rate)" in c_code
    assert "void waveforge_synth_note_on(WaveForgeSynth* s, int midi_note, float velocity)" in c_code
    assert "void waveforge_synth_note_off(WaveForgeSynth* s)" in c_code
    assert "void waveforge_synth_process(WaveForgeSynth* s, float* out_left, float* out_right, int num_samples)" in c_code
    assert "wf_polyblep" in c_code


def test_c_code_compilation_and_execution(tmp_path):
    compiler = CCompilerDriver.find_c_compiler()
    if not compiler:
        pytest.skip("No C compiler (clang or gcc) found on system PATH.")

    g = create_acid_303_patch()
    gen = CCodeGenerator(g)
    c_code = gen.generate_header()

    out_exe = str(tmp_path / "test_synth_runner.exe")
    success, res = CCompilerDriver.compile_standalone_c(c_code, output_exe=out_exe, compiler=compiler)
    assert success, f"Compilation failed: {res}"
    assert os.path.exists(out_exe)

    # Run compiled native binary
    retcode, out_str = CCompilerDriver.run_standalone_exe(out_exe, cwd=str(tmp_path))
    assert retcode == 0, f"Executable failed with output: {out_str}"
    assert "Rendered 2.0s audio" in out_str

    # Assert rendered WAV was generated by the C executable
    out_wav = tmp_path / "standalone_synth_render.wav"
    assert os.path.exists(out_wav)
    assert os.path.getsize(out_wav) > 1000
