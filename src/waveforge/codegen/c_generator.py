"""Zero-dependency C99 / WebAssembly code generator for modular synthesizer graphs."""

from __future__ import annotations
import math
from typing import List, Dict, Any
from waveforge.graph.patch import NodeGraph
from waveforge.graph.node import (
    OscillatorNode,
    FilterNode,
    ADSRNode,
    VCANode,
    LFONode,
    MixerNode,
    DelayNode,
    DistortionNode,
    ReverbNode,
    PannerNode,
    OutputNode,
)


class CCodeGenerator:
    """Transpiles a WaveForge NodeGraph into a standalone, single-file C99 header."""

    def __init__(self, graph: NodeGraph):
        self.graph = graph

    def generate_header(self, guard_name: str = "WAVEFORGE_SYNTH_H") -> str:
        """Generate complete C99 standalone header source code."""
        order = self.graph.get_topological_sort()

        # Connection mapping: (to_node, to_pin) -> (from_node, from_pin)
        wiring: Dict[tuple[str, str], tuple[str, str]] = {}
        for c in self.graph.connections:
            wiring[(c.to_node, c.to_pin)] = (c.from_node, c.from_pin)

        lines: List[str] = []

        # 1. Header Guard & Includes
        lines.append(f"/* Standalone DSP Synthesizer Header generated by WaveForge */")
        lines.append(f"/* Patch Name: {self.graph.name} */")
        lines.append(f"/* Author: {self.graph.author} */")
        lines.append(f"")
        lines.append(f"#ifndef {guard_name}")
        lines.append(f"#define {guard_name}")
        lines.append(f"")
        lines.append(f"#include <math.h>")
        lines.append(f"#include <stdint.h>")
        lines.append(f"#include <stdlib.h>")
        lines.append(f"#include <string.h>")
        lines.append(f"")
        lines.append(f"#ifndef M_PI")
        lines.append(f"#define M_PI 3.14159265358979323846f")
        lines.append(f"#endif")
        lines.append(f"")

        # 2. Math & DSP helper primitives
        lines.append(f"/* --- Core DSP Mathematical Helper Primitives --- */")
        lines.append(f"static inline float wf_polyblep(float t, float dt) {{")
        lines.append(f"    if (dt <= 0.0f) return 0.0f;")
        lines.append(f"    if (t < dt) {{")
        lines.append(f"        float x = t / dt;")
        lines.append(f"        return 2.0f * x - x * x - 1.0f;")
        lines.append(f"    }} else if (t > (1.0f - dt)) {{")
        lines.append(f"        float x = (t - 1.0f) / dt;")
        lines.append(f"        return x * x + 2.0f * x + 1.0f;")
        lines.append(f"    }}")
        lines.append(f"    return 0.0f;")
        lines.append(f"}}")
        lines.append(f"")
        lines.append(f"static inline float wf_clamp(float val, float min_val, float max_val) {{")
        lines.append(f"    if (val < min_val) return min_val;")
        lines.append(f"    if (val > max_val) return max_val;")
        lines.append(f"    return val;")
        lines.append(f"}}")
        lines.append(f"")
        lines.append(f"static inline float wf_midi_to_freq(int note) {{")
        lines.append(f"    return 440.0f * powf(2.0f, (float)(note - 69) / 12.0f);")
        lines.append(f"}}")
        lines.append(f"")

        # 3. Synthesizer State Structure
        lines.append(f"/* --- Synthesizer State Definition --- */")
        lines.append(f"typedef struct {{")
        lines.append(f"    float sample_rate;")
        lines.append(f"    int active_note;")
        lines.append(f"    float note_velocity;")
        lines.append(f"")

        # Allocate state for each node
        for nid, node in self.graph.nodes.items():
            lines.append(f"    /* Node: {nid} ({node.TYPE_ID}) */")
            if isinstance(node, OscillatorNode):
                lines.append(f"    float {nid}_phase;")
                lines.append(f"    float {nid}_frequency;")
                lines.append(f"    float {nid}_pulse_width;")
                lines.append(f"    int   {nid}_waveform; /* 0=sine, 1=saw, 2=square, 3=triangle, 4=noise */")
                lines.append(f"    float {nid}_tri_integrator;")
                lines.append(f"    uint32_t {nid}_rng_state;")
            elif isinstance(node, FilterNode):
                lines.append(f"    float {nid}_cutoff_hz;")
                lines.append(f"    float {nid}_q;")
                lines.append(f"    float {nid}_gain_db;")
                lines.append(f"    int   {nid}_filter_type; /* 0=lowpass, 1=highpass, 2=bandpass, 3=notch */")
                lines.append(f"    float {nid}_z1;")
                lines.append(f"    float {nid}_z2;")
                lines.append(f"    float {nid}_b0, {nid}_b1, {nid}_b2, {nid}_a1, {nid}_a2;")
            elif isinstance(node, ADSRNode):
                lines.append(f"    float {nid}_attack;")
                lines.append(f"    float {nid}_decay;")
                lines.append(f"    float {nid}_sustain;")
                lines.append(f"    float {nid}_release;")
                lines.append(f"    int   {nid}_stage; /* 0=idle, 1=attack, 2=decay, 3=sustain, 4=release */")
                lines.append(f"    float {nid}_current_value;")
                lines.append(f"    float {nid}_attack_coef;")
                lines.append(f"    float {nid}_decay_coef;")
                lines.append(f"    float {nid}_release_coef;")
            elif isinstance(node, VCANode):
                lines.append(f"    float {nid}_gain;")
            elif isinstance(node, LFONode):
                lines.append(f"    float {nid}_rate_hz;")
                lines.append(f"    float {nid}_phase;")
                lines.append(f"    float {nid}_depth;")
                lines.append(f"    int   {nid}_waveform;")
            elif isinstance(node, MixerNode):
                lines.append(f"    float {nid}_ch1_gain, {nid}_ch2_gain, {nid}_ch3_gain, {nid}_ch4_gain, {nid}_master_gain;")
            elif isinstance(node, DelayNode):
                lines.append(f"    float {nid}_time_sec;")
                lines.append(f"    float {nid}_feedback;")
                lines.append(f"    float {nid}_damping;")
                lines.append(f"    float {nid}_mix;")
                lines.append(f"    float {nid}_buf_l[65536];")
                lines.append(f"    float {nid}_buf_r[65536];")
                lines.append(f"    int   {nid}_write_idx;")
                lines.append(f"    float {nid}_damp_l;")
                lines.append(f"    float {nid}_damp_r;")
            elif isinstance(node, DistortionNode):
                lines.append(f"    float {nid}_drive;")
                lines.append(f"    float {nid}_mix;")
                lines.append(f"    int   {nid}_type; /* 0=tanh, 1=hard_clip, 2=cubic, 3=diode, 4=fold */")
                lines.append(f"    float {nid}_dc_state;")
            elif isinstance(node, ReverbNode):
                lines.append(f"    float {nid}_room_size;")
                lines.append(f"    float {nid}_damping;")
                lines.append(f"    float {nid}_wet;")
                lines.append(f"    float {nid}_dry;")
                lines.append(f"    float {nid}_comb_buf[8][2048];")
                lines.append(f"    int   {nid}_comb_idx[8];")
                lines.append(f"    float {nid}_comb_filter[8];")
                lines.append(f"    float {nid}_ap_buf[4][1024];")
                lines.append(f"    int   {nid}_ap_idx[4];")
            elif isinstance(node, PannerNode):
                lines.append(f"    float {nid}_pan;")
            elif isinstance(node, OutputNode):
                lines.append(f"    float {nid}_master_volume;")
                lines.append(f"    int   {nid}_limiter_enabled;")

        lines.append(f"}} WaveForgeSynth;")
        lines.append(f"")

        # 4. Filter coefficient calculation helper in C
        lines.append(f"/* Compute RBJ Filter Coefficients in C */")
        lines.append(f"static void wf_compute_filter_coeffs(WaveForgeSynth* s, const char* node_id) {{")
        for nid, node in self.graph.nodes.items():
            if isinstance(node, FilterNode):
                lines.append(f"    if (strcmp(node_id, \"{nid}\") == 0) {{")
                lines.append(f"        float f0 = wf_clamp(s->{nid}_cutoff_hz, 10.0f, s->sample_rate * 0.495f);")
                lines.append(f"        float q = wf_clamp(s->{nid}_q, 0.05f, 30.0f);")
                lines.append(f"        float w0 = 2.0f * M_PI * f0 / s->sample_rate;")
                lines.append(f"        float cos_w = cosf(w0);")
                lines.append(f"        float sin_w = sinf(w0);")
                lines.append(f"        float alpha = sin_w / (2.0f * q);")
                lines.append(f"        float b0 = 0.0f, b1 = 0.0f, b2 = 0.0f, a0 = 1.0f, a1 = 0.0f, a2 = 0.0f;")
                lines.append(f"        if (s->{nid}_filter_type == 0) {{ /* Lowpass */")
                lines.append(f"            b0 = (1.0f - cos_w) * 0.5f;")
                lines.append(f"            b1 = 1.0f - cos_w;")
                lines.append(f"            b2 = (1.0f - cos_w) * 0.5f;")
                lines.append(f"            a0 = 1.0f + alpha;")
                lines.append(f"            a1 = -2.0f * cos_w;")
                lines.append(f"            a2 = 1.0f - alpha;")
                lines.append(f"        }} else if (s->{nid}_filter_type == 1) {{ /* Highpass */")
                lines.append(f"            b0 = (1.0f + cos_w) * 0.5f;")
                lines.append(f"            b1 = -(1.0f + cos_w);")
                lines.append(f"            b2 = (1.0f + cos_w) * 0.5f;")
                lines.append(f"            a0 = 1.0f + alpha;")
                lines.append(f"            a1 = -2.0f * cos_w;")
                lines.append(f"            a2 = 1.0f - alpha;")
                lines.append(f"        }} else {{ /* Bandpass */")
                lines.append(f"            b0 = alpha; b1 = 0.0f; b2 = -alpha;")
                lines.append(f"            a0 = 1.0f + alpha; a1 = -2.0f * cos_w; a2 = 1.0f - alpha;")
                lines.append(f"        }}")
                lines.append(f"        float inv_a0 = 1.0f / a0;")
                lines.append(f"        s->{nid}_b0 = b0 * inv_a0;")
                lines.append(f"        s->{nid}_b1 = b1 * inv_a0;")
                lines.append(f"        s->{nid}_b2 = b2 * inv_a0;")
                lines.append(f"        s->{nid}_a1 = a1 * inv_a0;")
                lines.append(f"        s->{nid}_a2 = a2 * inv_a0;")
                lines.append(f"        return;")
                lines.append(f"    }}")
        lines.append(f"}}")
        lines.append(f"")

        # 5. Initialization Function
        lines.append(f"/* Initialize synthesizer structure and coefficients */")
        lines.append(f"static void waveforge_synth_init(WaveForgeSynth* s, float sample_rate) {{")
        lines.append(f"    memset(s, 0, sizeof(WaveForgeSynth));")
        lines.append(f"    s->sample_rate = sample_rate > 0.0f ? sample_rate : 44100.0f;")
        lines.append(f"    s->active_note = -1;")
        lines.append(f"    s->note_velocity = 0.0f;")
        lines.append(f"")

        # Set default values for each node
        for nid, node in self.graph.nodes.items():
            lines.append(f"    /* Init {nid} */")
            if isinstance(node, OscillatorNode):
                wf_map = {"sine": 0, "saw": 1, "square": 2, "triangle": 3, "noise": 4}
                wf_code = wf_map.get(node.params.get("waveform", "saw"), 1)
                lines.append(f"    s->{nid}_waveform = {wf_code};")
                lines.append(f"    s->{nid}_frequency = {float(node.params.get('frequency', 220.0))}f;")
                lines.append(f"    s->{nid}_pulse_width = {float(node.params.get('pulse_width', 0.5))}f;")
                lines.append(f"    s->{nid}_rng_state = 123456789U;")
            elif isinstance(node, FilterNode):
                ft_map = {"lowpass": 0, "highpass": 1, "bandpass": 2, "notch": 3}
                ft_code = ft_map.get(node.params.get("filter_type", "lowpass"), 0)
                lines.append(f"    s->{nid}_filter_type = {ft_code};")
                lines.append(f"    s->{nid}_cutoff_hz = {float(node.params.get('cutoff_hz', 1200.0))}f;")
                lines.append(f"    s->{nid}_q = {float(node.params.get('q', 1.5))}f;")
                lines.append(f"    s->{nid}_gain_db = {float(node.params.get('gain_db', 0.0))}f;")
                lines.append(f"    wf_compute_filter_coeffs(s, \"{nid}\");")
            elif isinstance(node, ADSRNode):
                lines.append(f"    s->{nid}_attack = {float(node.params.get('attack', 0.01))}f;")
                lines.append(f"    s->{nid}_decay = {float(node.params.get('decay', 0.15))}f;")
                lines.append(f"    s->{nid}_sustain = {float(node.params.get('sustain', 0.6))}f;")
                lines.append(f"    s->{nid}_release = {float(node.params.get('release', 0.25))}f;")
                lines.append(f"    s->{nid}_attack_coef = expf(-1.0f / (s->{nid}_attack * s->sample_rate * 0.36f));")
                lines.append(f"    s->{nid}_decay_coef = expf(-1.0f / (s->{nid}_decay * s->sample_rate * 0.25f));")
                lines.append(f"    s->{nid}_release_coef = expf(-1.0f / (s->{nid}_release * s->sample_rate * 0.25f));")
            elif isinstance(node, VCANode):
                lines.append(f"    s->{nid}_gain = {float(node.params.get('gain', 1.0))}f;")
            elif isinstance(node, LFONode):
                wf_map = {"sine": 0, "triangle": 1, "saw_up": 2, "saw_down": 3, "square": 4}
                wf_code = wf_map.get(node.params.get("waveform", "sine"), 0)
                lines.append(f"    s->{nid}_rate_hz = {float(node.params.get('rate_hz', 2.5))}f;")
                lines.append(f"    s->{nid}_depth = {float(node.params.get('depth', 1.0))}f;")
                lines.append(f"    s->{nid}_waveform = {wf_code};")
            elif isinstance(node, MixerNode):
                lines.append(f"    s->{nid}_ch1_gain = {float(node.params.get('ch1_gain', 0.8))}f;")
                lines.append(f"    s->{nid}_ch2_gain = {float(node.params.get('ch2_gain', 0.8))}f;")
                lines.append(f"    s->{nid}_ch3_gain = {float(node.params.get('ch3_gain', 0.8))}f;")
                lines.append(f"    s->{nid}_ch4_gain = {float(node.params.get('ch4_gain', 0.8))}f;")
                lines.append(f"    s->{nid}_master_gain = {float(node.params.get('master_gain', 1.0))}f;")
            elif isinstance(node, DelayNode):
                lines.append(f"    s->{nid}_time_sec = {float(node.params.get('time_sec', 0.3))}f;")
                lines.append(f"    s->{nid}_feedback = {float(node.params.get('feedback', 0.45))}f;")
                lines.append(f"    s->{nid}_damping = {float(node.params.get('damping', 0.25))}f;")
                lines.append(f"    s->{nid}_mix = {float(node.params.get('mix', 0.35))}f;")
            elif isinstance(node, DistortionNode):
                lines.append(f"    s->{nid}_drive = {float(node.params.get('drive', 2.5))}f;")
                lines.append(f"    s->{nid}_mix = {float(node.params.get('mix', 1.0))}f;")
                lines.append(f"    s->{nid}_type = 0; /* tanh */")
            elif isinstance(node, ReverbNode):
                lines.append(f"    s->{nid}_room_size = {float(node.params.get('room_size', 0.6))}f;")
                lines.append(f"    s->{nid}_damping = {float(node.params.get('damping', 0.4))}f;")
                lines.append(f"    s->{nid}_wet = {float(node.params.get('wet', 0.35))}f;")
                lines.append(f"    s->{nid}_dry = {float(node.params.get('dry', 0.75))}f;")
            elif isinstance(node, PannerNode):
                lines.append(f"    s->{nid}_pan = {float(node.params.get('pan', 0.0))}f;")
            elif isinstance(node, OutputNode):
                lines.append(f"    s->{nid}_master_volume = {float(node.params.get('master_volume', 0.85))}f;")
                lines.append(f"    s->{nid}_limiter_enabled = {1 if node.params.get('limiter_enabled', True) else 0};")

        lines.append(f"}}")
        lines.append(f"")

        # 6. Note On / Note Off
        lines.append(f"/* Trigger Note On */")
        lines.append(f"static void waveforge_synth_note_on(WaveForgeSynth* s, int midi_note, float velocity) {{")
        lines.append(f"    s->active_note = midi_note;")
        lines.append(f"    s->note_velocity = velocity;")
        lines.append(f"    float freq = wf_midi_to_freq(midi_note);")
        for nid, node in self.graph.nodes.items():
            if isinstance(node, OscillatorNode):
                lines.append(f"    s->{nid}_frequency = freq;")
            elif isinstance(node, ADSRNode):
                lines.append(f"    s->{nid}_stage = 1; /* ATTACK */")
        lines.append(f"}}")
        lines.append(f"")

        lines.append(f"/* Trigger Note Off */")
        lines.append(f"static void waveforge_synth_note_off(WaveForgeSynth* s) {{")
        lines.append(f"    s->active_note = -1;")
        for nid, node in self.graph.nodes.items():
            if isinstance(node, ADSRNode):
                lines.append(f"    if (s->{nid}_stage != 0) s->{nid}_stage = 4; /* RELEASE */")
        lines.append(f"}}")
        lines.append(f"")

        # 7. Real-Time Processing Function
        lines.append(f"/* Process buffer of stereo audio samples */")
        lines.append(f"static void waveforge_synth_process(WaveForgeSynth* s, float* out_left, float* out_right, int num_samples) {{")
        lines.append(f"    for (int i = 0; i < num_samples; i++) {{")

        # Helper to resolve pin variable
        def pin_var(n_id: str, p_name: str) -> str:
            # Check if this input pin is wired
            if (n_id, p_name) in wiring:
                src_n, src_p = wiring[(n_id, p_name)]
                return f"node_{src_n}_{src_p}"
            # Otherwise use default
            return f"0.0f"

        # Generate sample-by-sample DSP step for nodes in topological order
        for nid in order:
            node = self.graph.nodes[nid]
            lines.append(f"        /* Node: {nid} ({node.TYPE_ID}) */")

            if isinstance(node, OscillatorNode):
                lines.append(f"        float node_{nid}_out = 0.0f;")
                lines.append(f"        float {nid}_dt = s->{nid}_frequency / s->sample_rate;")
                lines.append(f"        float {nid}_p = s->{nid}_phase + {pin_var(nid, 'pm')};")
                lines.append(f"        {nid}_p = {nid}_p - floorf({nid}_p);")
                lines.append(f"        if (s->{nid}_waveform == 0) {{ /* Sine */")
                lines.append(f"            node_{nid}_out = sinf(2.0f * M_PI * {nid}_p);")
                lines.append(f"        }} else if (s->{nid}_waveform == 1) {{ /* Saw */")
                lines.append(f"            float naive_saw = 2.0f * {nid}_p - 1.0f;")
                lines.append(f"            node_{nid}_out = naive_saw - wf_polyblep({nid}_p, {nid}_dt);")
                lines.append(f"        }} else if (s->{nid}_waveform == 2) {{ /* Square */")
                lines.append(f"            float pw = s->{nid}_pulse_width;")
                lines.append(f"            float naive_sq = ({nid}_p < pw) ? 1.0f : -1.0f;")
                lines.append(f"            float p_shift = {nid}_p - pw + 1.0f;")
                lines.append(f"            p_shift = p_shift - floorf(p_shift);")
                lines.append(f"            node_{nid}_out = naive_sq + wf_polyblep({nid}_p, {nid}_dt) - wf_polyblep(p_shift, {nid}_dt);")
                lines.append(f"        }} else if (s->{nid}_waveform == 3) {{ /* Triangle */")
                lines.append(f"            float naive_sq = ({nid}_p < 0.5f) ? 1.0f : -1.0f;")
                lines.append(f"            float p_shift = {nid}_p - 0.5f + 1.0f;")
                lines.append(f"            p_shift = p_shift - floorf(p_shift);")
                lines.append(f"            float sq = naive_sq + wf_polyblep({nid}_p, {nid}_dt) - wf_polyblep(p_shift, {nid}_dt);")
                lines.append(f"            s->{nid}_tri_integrator += 4.0f * {nid}_dt * sq;")
                lines.append(f"            s->{nid}_tri_integrator *= 0.9995f;")
                lines.append(f"            node_{nid}_out = wf_clamp(s->{nid}_tri_integrator, -1.0f, 1.0f);")
                lines.append(f"        }} else {{ /* White/Pink Noise via LCG */")
                lines.append(f"            s->{nid}_rng_state = s->{nid}_rng_state * 1664525U + 1013904223U;")
                lines.append(f"            node_{nid}_out = ((float)(s->{nid}_rng_state & 0x7FFFFFFFU) / 1073741824.0f) - 1.0f;")
                lines.append(f"        }}")
                lines.append(f"        s->{nid}_phase += {nid}_dt;")
                lines.append(f"        if (s->{nid}_phase >= 1.0f) s->{nid}_phase -= 1.0f;")

            elif isinstance(node, FilterNode):
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float node_{nid}_out = s->{nid}_b0 * node_{nid}_in + s->{nid}_z1;")
                lines.append(f"        s->{nid}_z1 = s->{nid}_b1 * node_{nid}_in - s->{nid}_a1 * node_{nid}_out + s->{nid}_z2;")
                lines.append(f"        s->{nid}_z2 = s->{nid}_b2 * node_{nid}_in - s->{nid}_a2 * node_{nid}_out;")

            elif isinstance(node, ADSRNode):
                lines.append(f"        float node_{nid}_out = 0.0f;")
                lines.append(f"        if (s->{nid}_stage == 1) {{ /* ATTACK */")
                lines.append(f"            s->{nid}_current_value = 1.5f + (s->{nid}_current_value - 1.5f) * s->{nid}_attack_coef;")
                lines.append(f"            if (s->{nid}_current_value >= 1.0f) {{")
                lines.append(f"                s->{nid}_current_value = 1.0f;")
                lines.append(f"                s->{nid}_stage = 2; /* DECAY */")
                lines.append(f"            }}")
                lines.append(f"        }} else if (s->{nid}_stage == 2) {{ /* DECAY */")
                lines.append(f"            s->{nid}_current_value = s->{nid}_sustain + (s->{nid}_current_value - s->{nid}_sustain) * s->{nid}_decay_coef;")
                lines.append(f"            if (fabsf(s->{nid}_current_value - s->{nid}_sustain) <= 0.001f) {{")
                lines.append(f"                s->{nid}_current_value = s->{nid}_sustain;")
                lines.append(f"                s->{nid}_stage = 3; /* SUSTAIN */")
                lines.append(f"            }}")
                lines.append(f"        }} else if (s->{nid}_stage == 3) {{ /* SUSTAIN */")
                lines.append(f"            s->{nid}_current_value = s->{nid}_sustain;")
                lines.append(f"        }} else if (s->{nid}_stage == 4) {{ /* RELEASE */")
                lines.append(f"            s->{nid}_current_value = -0.05f + (s->{nid}_current_value - (-0.05f)) * s->{nid}_release_coef;")
                lines.append(f"            if (s->{nid}_current_value <= 0.0f) {{")
                lines.append(f"                s->{nid}_current_value = 0.0f;")
                lines.append(f"                s->{nid}_stage = 0; /* IDLE */")
                lines.append(f"            }}")
                lines.append(f"        }}")
                lines.append(f"        node_{nid}_out = s->{nid}_current_value;")

            elif isinstance(node, VCANode):
                cv_val = pin_var(nid, "cv") if (nid, "cv") in wiring else "1.0f"
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float node_{nid}_out = node_{nid}_in * {cv_val} * s->{nid}_gain;")

            elif isinstance(node, LFONode):
                lines.append(f"        float node_{nid}_out = sinf(2.0f * M_PI * s->{nid}_phase) * s->{nid}_depth;")
                lines.append(f"        s->{nid}_phase += (s->{nid}_rate_hz / s->sample_rate);")
                lines.append(f"        if (s->{nid}_phase >= 1.0f) s->{nid}_phase -= 1.0f;")

            elif isinstance(node, MixerNode):
                lines.append(f"        float node_{nid}_out = ({pin_var(nid, 'in1')} * s->{nid}_ch1_gain + {pin_var(nid, 'in2')} * s->{nid}_ch2_gain + {pin_var(nid, 'in3')} * s->{nid}_ch3_gain + {pin_var(nid, 'in4')} * s->{nid}_ch4_gain) * s->{nid}_master_gain;")

            elif isinstance(node, DelayNode):
                lines.append(f"        float node_{nid}_in_l = {pin_var(nid, 'in_l')};")
                lines.append(f"        float node_{nid}_in_r = {pin_var(nid, 'in_r') if (nid, 'in_r') in wiring else f'node_{nid}_in_l'};")
                lines.append(f"        int {nid}_d_samples = (int)(s->{nid}_time_sec * s->sample_rate) & 0xFFFF;")
                lines.append(f"        int {nid}_read_idx = (s->{nid}_write_idx - {nid}_d_samples) & 0xFFFF;")
                lines.append(f"        float {nid}_delayed_l = s->{nid}_buf_l[{nid}_read_idx];")
                lines.append(f"        float {nid}_delayed_r = s->{nid}_buf_r[{nid}_read_idx];")
                lines.append(f"        s->{nid}_damp_l = (1.0f - s->{nid}_damping) * {nid}_delayed_l + s->{nid}_damping * s->{nid}_damp_l;")
                lines.append(f"        s->{nid}_damp_r = (1.0f - s->{nid}_damping) * {nid}_delayed_r + s->{nid}_damping * s->{nid}_damp_r;")
                lines.append(f"        s->{nid}_buf_l[s->{nid}_write_idx] = tanhf(node_{nid}_in_l + s->{nid}_damp_r * s->{nid}_feedback);")
                lines.append(f"        s->{nid}_buf_r[s->{nid}_write_idx] = tanhf(node_{nid}_in_r + s->{nid}_damp_l * s->{nid}_feedback);")
                lines.append(f"        s->{nid}_write_idx = (s->{nid}_write_idx + 1) & 0xFFFF;")
                lines.append(f"        float node_{nid}_out_l = (1.0f - s->{nid}_mix) * node_{nid}_in_l + s->{nid}_mix * {nid}_delayed_l;")
                lines.append(f"        float node_{nid}_out_r = (1.0f - s->{nid}_mix) * node_{nid}_in_r + s->{nid}_mix * {nid}_delayed_r;")

            elif isinstance(node, DistortionNode):
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float node_{nid}_out = (1.0f - s->{nid}_mix) * node_{nid}_in + s->{nid}_mix * tanhf(s->{nid}_drive * node_{nid}_in);")

            elif isinstance(node, ReverbNode):
                lines.append(f"        float node_{nid}_in_l = {pin_var(nid, 'in_l')};")
                lines.append(f"        float node_{nid}_in_r = {pin_var(nid, 'in_r') if (nid, 'in_r') in wiring else f'node_{nid}_in_l'};")
                lines.append(f"        float node_{nid}_out_l = node_{nid}_in_l * s->{nid}_dry;")
                lines.append(f"        float node_{nid}_out_r = node_{nid}_in_r * s->{nid}_dry;")

            elif isinstance(node, PannerNode):
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float {nid}_ang = (s->{nid}_pan + 1.0f) * (M_PI * 0.25f);")
                lines.append(f"        float node_{nid}_out_l = node_{nid}_in * cosf({nid}_ang);")
                lines.append(f"        float node_{nid}_out_r = node_{nid}_in * sinf({nid}_ang);")

            elif isinstance(node, OutputNode):
                lines.append(f"        float node_{nid}_left = {pin_var(nid, 'left')} * s->{nid}_master_volume;")
                lines.append(f"        float node_{nid}_right = {pin_var(nid, 'right') if (nid, 'right') in wiring else f'node_{nid}_left'} * s->{nid}_master_volume;")
                lines.append(f"        if (s->{nid}_limiter_enabled) {{")
                lines.append(f"            node_{nid}_left = tanhf(node_{nid}_left);")
                lines.append(f"            node_{nid}_right = tanhf(node_{nid}_right);")
                lines.append(f"        }}")
                lines.append(f"        out_left[i] = node_{nid}_left;")
                lines.append(f"        out_right[i] = node_{nid}_right;")

        lines.append(f"    }}")
        lines.append(f"}}")
        lines.append(f"")

        # 8. Standalone Runner and WAV Writer (if WAVEFORGE_STANDALONE defined)
        lines.append(f"/* Standalone test binary and WAV writer */")
        lines.append(f"#ifdef WAVEFORGE_STANDALONE")
        lines.append(f"#include <stdio.h>")
        lines.append(f"")
        lines.append(f"static void wf_write_wav(const char* filename, float* left, float* right, int num_samples, int sample_rate) {{")
        lines.append(f"    FILE* f = fopen(filename, \"wb\");")
        lines.append(f"    if (!f) return;")
        lines.append(f"    int byte_rate = sample_rate * 2 * 2; /* 16-bit stereo */")
        lines.append(f"    int data_size = num_samples * 2 * 2;")
        lines.append(f"    int riff_size = 36 + data_size;")
        lines.append(f"    fwrite(\"RIFF\", 1, 4, f);")
        lines.append(f"    fwrite(&riff_size, 4, 1, f);")
        lines.append(f"    fwrite(\"WAVEfmt \", 1, 8, f);")
        lines.append(f"    int subchunk1_size = 16;")
        lines.append(f"    short audio_format = 1; /* PCM */")
        lines.append(f"    short num_channels = 2;")
        lines.append(f"    short block_align = 4;")
        lines.append(f"    short bits_per_sample = 16;")
        lines.append(f"    fwrite(&subchunk1_size, 4, 1, f);")
        lines.append(f"    fwrite(&audio_format, 2, 1, f);")
        lines.append(f"    fwrite(&num_channels, 2, 1, f);")
        lines.append(f"    fwrite(&sample_rate, 4, 1, f);")
        lines.append(f"    fwrite(&byte_rate, 4, 1, f);")
        lines.append(f"    fwrite(&block_align, 2, 1, f);")
        lines.append(f"    fwrite(&bits_per_sample, 2, 1, f);")
        lines.append(f"    fwrite(\"data\", 1, 4, f);")
        lines.append(f"    fwrite(&data_size, 4, 1, f);")
        lines.append(f"    for (int i = 0; i < num_samples; i++) {{")
        lines.append(f"        short sl = (short)(wf_clamp(left[i], -1.0f, 1.0f) * 32767.0f);")
        lines.append(f"        short sr = (short)(wf_clamp(right[i], -1.0f, 1.0f) * 32767.0f);")
        lines.append(f"        fwrite(&sl, 2, 1, f);")
        lines.append(f"        fwrite(&sr, 2, 1, f);")
        lines.append(f"    }}")
        lines.append(f"    fclose(f);")
        lines.append(f"}}")
        lines.append(f"")
        lines.append(f"int main(int argc, char** argv) {{")
        lines.append(f"    printf(\"Initializing WaveForge Standalone Synth C Engine...\\n\");")
        lines.append(f"    WaveForgeSynth synth;")
        lines.append(f"    int sample_rate = 44100;")
        lines.append(f"    waveforge_synth_init(&synth, (float)sample_rate);")
        lines.append(f"    waveforge_synth_note_on(&synth, 60, 0.9f); /* Middle C */")
        lines.append(f"    int total_samples = sample_rate * 2; /* 2.0 seconds */")
        lines.append(f"    float* buf_l = (float*)malloc(sizeof(float) * total_samples);")
        lines.append(f"    float* buf_r = (float*)malloc(sizeof(float) * total_samples);")
        lines.append(f"    int block_size = 128;")
        lines.append(f"    for (int i = 0; i < total_samples; i += block_size) {{")
        lines.append(f"        if (i >= (int)(sample_rate * 1.5)) waveforge_synth_note_off(&synth);")
        lines.append(f"        int chunk = (total_samples - i < block_size) ? total_samples - i : block_size;")
        lines.append(f"        waveforge_synth_process(&synth, buf_l + i, buf_r + i, chunk);")
        lines.append(f"    }}")
        lines.append(f"    const char* out_wav = \"standalone_synth_render.wav\";")
        lines.append(f"    wf_write_wav(out_wav, buf_l, buf_r, total_samples, sample_rate);")
        lines.append(f"    printf(\"Rendered 2.0s audio to %s successfully!\\n\", out_wav);")
        lines.append(f"    free(buf_l);")
        lines.append(f"    free(buf_r);")
        lines.append(f"    return 0;")
        lines.append(f"}}")
        lines.append(f"#endif /* WAVEFORGE_STANDALONE */")
        lines.append(f"")
        lines.append(f"#endif /* {guard_name} */")
        lines.append(f"")

        return "\n".join(lines)
