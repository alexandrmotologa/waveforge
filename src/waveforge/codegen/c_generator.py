        # 7. Real-Time Processing Function
        lines.append(f"/* Process buffer of stereo audio samples */")
        lines.append(f"static void waveforge_synth_process(WaveForgeSynth* s, float* out_left, float* out_right, int num_samples) {{")
        lines.append(f"    for (int i = 0; i < num_samples; i++) {{")

        # Helper to resolve pin variable
        def pin_var(n_id: str, p_name: str) -> str:
            if (n_id, p_name) in wiring:
                src_n, src_p = wiring[(n_id, p_name)]
                return f"node_{src_n}_{src_p}"
            return f"0.0f"

        # Generate sample-by-sample DSP step for nodes in topological order
        for nid in order:
            node = self.graph.nodes[nid]
            lines.append(f"        /* Node: {nid} ({node.TYPE_ID}) */")

            if isinstance(node, OscillatorNode):
                lines.append(f"        float node_{nid}_out = 0.0f;")
                lines.append(f"        float {nid}_dt = s->{nid}_frequency / s->sample_rate;")
                lines.append(f"        float {nid}_p = s->{nid}_phase + {pin_var(nid, 'pm')};")
                lines.append(f"        {nid}_p = {nid}_p - floorf({nid}_p);")
                lines.append(f"        if (s->{nid}_waveform == 0) {{ /* Sine */")
                lines.append(f"            node_{nid}_out = sinf(2.0f * M_PI * {nid}_p);")
                lines.append(f"        }} else if (s->{nid}_waveform == 1) {{ /* Saw */")
                lines.append(f"            float naive_saw = 2.0f * {nid}_p - 1.0f;")
                lines.append(f"            node_{nid}_out = naive_saw - wf_polyblep({nid}_p, {nid}_dt);")
                lines.append(f"        }} else if (s->{nid}_waveform == 2) {{ /* Square */")
                lines.append(f"            float pw = s->{nid}_pulse_width;")
                lines.append(f"            float naive_sq = ({nid}_p < pw) ? 1.0f : -1.0f;")
                lines.append(f"            float p_shift = {nid}_p - pw + 1.0f;")
                lines.append(f"            p_shift = p_shift - floorf(p_shift);")
                lines.append(f"            node_{nid}_out = naive_sq + wf_polyblep({nid}_p, {nid}_dt) - wf_polyblep(p_shift, {nid}_dt);")
                lines.append(f"        }} else if (s->{nid}_waveform == 3) {{ /* Triangle */")
                lines.append(f"            float naive_sq = ({nid}_p < 0.5f) ? 1.0f : -1.0f;")
                lines.append(f"            float p_shift = {nid}_p - 0.5f + 1.0f;")
                lines.append(f"            p_shift = p_shift - floorf(p_shift);")
                lines.append(f"            float sq = naive_sq + wf_polyblep({nid}_p, {nid}_dt) - wf_polyblep(p_shift, {nid}_dt);")
                lines.append(f"            s->{nid}_tri_integrator += 4.0f * {nid}_dt * sq;")
                lines.append(f"            s->{nid}_tri_integrator *= 0.9995f;")
                lines.append(f"            node_{nid}_out = wf_clamp(s->{nid}_tri_integrator, -1.0f, 1.0f);")
                lines.append(f"        }} else {{ /* White/Pink Noise via LCG */")
                lines.append(f"            s->{nid}_rng_state = s->{nid}_rng_state * 1664525U + 1013904223U;")
                lines.append(f"            node_{nid}_out = ((float)(s->{nid}_rng_state & 0x7FFFFFFFU) / 1073741824.0f) - 1.0f;")
                lines.append(f"        }}")
                lines.append(f"        s->{nid}_phase += {nid}_dt;")
                lines.append(f"        if (s->{nid}_phase >= 1.0f) s->{nid}_phase -= 1.0f;")

            elif isinstance(node, FilterNode):
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float node_{nid}_out = s->{nid}_b0 * node_{nid}_in + s->{nid}_z1;")
                lines.append(f"        s->{nid}_z1 = s->{nid}_b1 * node_{nid}_in - s->{nid}_a1 * node_{nid}_out + s->{nid}_z2;")
                lines.append(f"        s->{nid}_z2 = s->{nid}_b2 * node_{nid}_in - s->{nid}_a2 * node_{nid}_out;")

            elif isinstance(node, ADSRNode):
                lines.append(f"        float node_{nid}_out = 0.0f;")
                lines.append(f"        if (s->{nid}_stage == 1) {{ /* ATTACK */")
                lines.append(f"            s->{nid}_current_value = 1.5f + (s->{nid}_current_value - 1.5f) * s->{nid}_attack_coef;")
                lines.append(f"            if (s->{nid}_current_value >= 1.0f) {{")
                lines.append(f"                s->{nid}_current_value = 1.0f;")
                lines.append(f"                s->{nid}_stage = 2; /* DECAY */")
                lines.append(f"            }}")
                lines.append(f"        }} else if (s->{nid}_stage == 2) {{ /* DECAY */")
                lines.append(f"            s->{nid}_current_value = s->{nid}_sustain + (s->{nid}_current_value - s->{nid}_sustain) * s->{nid}_decay_coef;")
                lines.append(f"            if (fabsf(s->{nid}_current_value - s->{nid}_sustain) <= 0.001f) {{")
                lines.append(f"                s->{nid}_current_value = s->{nid}_sustain;")
                lines.append(f"                s->{nid}_stage = 3; /* SUSTAIN */")
                lines.append(f"            }}")
                lines.append(f"        }} else if (s->{nid}_stage == 3) {{ /* SUSTAIN */")
                lines.append(f"            s->{nid}_current_value = s->{nid}_sustain;")
                lines.append(f"        }} else if (s->{nid}_stage == 4) {{ /* RELEASE */")
                lines.append(f"            s->{nid}_current_value = -0.05f + (s->{nid}_current_value - (-0.05f)) * s->{nid}_release_coef;")
                lines.append(f"            if (s->{nid}_current_value <= 0.0f) {{")
                lines.append(f"                s->{nid}_current_value = 0.0f;")
                lines.append(f"                s->{nid}_stage = 0; /* IDLE */")
                lines.append(f"            }}")
                lines.append(f"        }}")
                lines.append(f"        node_{nid}_out = s->{nid}_current_value;")

            elif isinstance(node, VCANode):
                cv_val = pin_var(nid, "cv") if (nid, "cv") in wiring else "1.0f"
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float node_{nid}_out = node_{nid}_in * {cv_val} * s->{nid}_gain;")

            elif isinstance(node, LFONode):
                lines.append(f"        float node_{nid}_out = sinf(2.0f * M_PI * s->{nid}_phase) * s->{nid}_depth;")
                lines.append(f"        s->{nid}_phase += (s->{nid}_rate_hz / s->sample_rate);")
                lines.append(f"        if (s->{nid}_phase >= 1.0f) s->{nid}_phase -= 1.0f;")

            elif isinstance(node, MixerNode):
                lines.append(f"        float node_{nid}_out = ({pin_var(nid, 'in1')} * s->{nid}_ch1_gain + {pin_var(nid, 'in2')} * s->{nid}_ch2_gain + {pin_var(nid, 'in3')} * s->{nid}_ch3_gain + {pin_var(nid, 'in4')} * s->{nid}_ch4_gain) * s->{nid}_master_gain;")

            elif isinstance(node, DelayNode):
                lines.append(f"        float node_{nid}_in_l = {pin_var(nid, 'in_l')};")
                lines.append(f"        float node_{nid}_in_r = {pin_var(nid, 'in_r') if (nid, 'in_r') in wiring else f'node_{nid}_in_l'};")
                lines.append(f"        int {nid}_d_samples = (int)(s->{nid}_time_sec * s->sample_rate) & 0xFFFF;")
                lines.append(f"        int {nid}_read_idx = (s->{nid}_write_idx - {nid}_d_samples) & 0xFFFF;")
                lines.append(f"        float {nid}_delayed_l = s->{nid}_buf_l[{nid}_read_idx];")
                lines.append(f"        float {nid}_delayed_r = s->{nid}_buf_r[{nid}_read_idx];")
                lines.append(f"        s->{nid}_damp_l = (1.0f - s->{nid}_damping) * {nid}_delayed_l + s->{nid}_damping * s->{nid}_damp_l;")
                lines.append(f"        s->{nid}_damp_r = (1.0f - s->{nid}_damping) * {nid}_delayed_r + s->{nid}_damping * s->{nid}_damp_r;")
                lines.append(f"        s->{nid}_buf_l[s->{nid}_write_idx] = tanhf(node_{nid}_in_l + s->{nid}_damp_r * s->{nid}_feedback);")
                lines.append(f"        s->{nid}_buf_r[s->{nid}_write_idx] = tanhf(node_{nid}_in_r + s->{nid}_damp_l * s->{nid}_feedback);")
                lines.append(f"        s->{nid}_write_idx = (s->{nid}_write_idx + 1) & 0xFFFF;")
                lines.append(f"        float node_{nid}_out_l = (1.0f - s->{nid}_mix) * node_{nid}_in_l + s->{nid}_mix * {nid}_delayed_l;")
                lines.append(f"        float node_{nid}_out_r = (1.0f - s->{nid}_mix) * node_{nid}_in_r + s->{nid}_mix * {nid}_delayed_r;")

            elif isinstance(node, DistortionNode):
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float node_{nid}_out = (1.0f - s->{nid}_mix) * node_{nid}_in + s->{nid}_mix * tanhf(s->{nid}_drive * node_{nid}_in);")

            elif isinstance(node, ReverbNode):
                lines.append(f"        float node_{nid}_in_l = {pin_var(nid, 'in_l')};")
                lines.append(f"        float node_{nid}_in_r = {pin_var(nid, 'in_r') if (nid, 'in_r') in wiring else f'node_{nid}_in_l'};")
                lines.append(f"        float node_{nid}_out_l = node_{nid}_in_l * s->{nid}_dry;")
                lines.append(f"        float node_{nid}_out_r = node_{nid}_in_r * s->{nid}_dry;")

            elif isinstance(node, PannerNode):
                lines.append(f"        float node_{nid}_in = {pin_var(nid, 'in')};")
                lines.append(f"        float {nid}_ang = (s->{nid}_pan + 1.0f) * (M_PI * 0.25f);")
                lines.append(f"        float node_{nid}_out_l = node_{nid}_in * cosf({nid}_ang);")
